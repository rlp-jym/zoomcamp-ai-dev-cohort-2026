"""PostgreSQL integration tests for the relay protocol.

These exercises are skipped unless ``RELAY_DATABASE_URL`` points at a real
PostgreSQL instance, so a plain ``pytest`` run stays on the SQLite scratch
database.  CI exports ``RELAY_DATABASE_URL`` and runs the whole suite again so
the PostgreSQL storage port (row locking, ``BEGIN IMMEDIATE`` seam, recovery)
gets end-to-end coverage.

Any instance 'air' can write to is fine; pytest drops and recreates all tables.
"""

